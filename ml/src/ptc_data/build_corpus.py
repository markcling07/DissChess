"""Writes a labelled test collection in the format the evaluation tool reads.

Run: python -m ptc_data.build_corpus corpus/synth-holdout --split holdout --boards 400
"""

import argparse
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter
from ptc_vision.board import to_placement

from ptc_data.assets import PIECE_SETS
from ptc_data.render import (
    compose_page,
    render_board,
    sample_position,
    sample_style,
    write_image,
)


def labelled_entry(index: int, split: str, rng: random.Random, out: Path) -> dict:
    style = sample_style(rng, split)
    size = rng.choice([rng.randint(200, 400), rng.randint(400, 800), rng.randint(800, 1100)])
    flipped = rng.random() < 0.3
    position, kind = sample_position(rng)
    render = render_board(rng, style, position, size, flipped)
    tags = list(render.tags) + [
        f"theme:{style.theme}",
        f"size:{size // 200 * 200}",
        f"position:{kind}",
    ]

    if rng.random() < 0.6:
        tags.append("page")
        frame = rng.choice([0, 0, rng.randint(2, 24)])
        image, (x, y, width, height) = compose_page(rng, render.image, frame)
    else:
        image, (x, y, width, height) = render.image, (0, 0, size, size)

    suffix = rng.choice([".png", ".png", ".jpg", ".webp"])
    name = f"images/board-{index:05}{suffix}"
    write_image(out / name, image, rng)

    corners = [
        {"x": x / image.width, "y": y / image.height},
        {"x": (x + width) / image.width, "y": y / image.height},
        {"x": (x + width) / image.width, "y": (y + height) / image.height},
        {"x": x / image.width, "y": (y + height) / image.height},
    ]
    return {
        "id": f"board-{index:05}",
        "image": name,
        "kind": "screenshot",
        "set_id": style.piece_set,
        "split": "holdout" if split == "holdout" else "dev",
        "source": "generated by ptc_data",
        "license": PIECE_SETS[style.piece_set][1],
        "placement": to_placement(render.board),
        "corners": corners,
        "tags": tags,
    }


def refusal_image(kind: str, split: str, rng: random.Random) -> Image.Image:
    style = sample_style(rng, split)
    if kind == "no_board":
        image = Image.new("RGB", (900, 600), (rng.randint(20, 240),) * 3)
        draw = ImageDraw.Draw(image)
        for row in range(rng.randint(5, 25)):
            draw.text(
                (30, 20 + row * 22), "Some text with no chessboard in it", fill=(128, 128, 128)
            )
        for _ in range(rng.randint(1, 6)):
            x, y = rng.randint(0, 800), rng.randint(0, 500)
            draw.rectangle([x, y, x + 90, y + 60], outline=(90, 90, 90))
        return image
    if kind == "noise":
        data = np.random.default_rng(rng.getrandbits(32)).integers(0, 255, (500, 700, 3))
        return Image.fromarray(data.astype("uint8"))
    if kind == "table":
        image = Image.new("RGB", (800, 800), (250, 250, 250))
        draw = ImageDraw.Draw(image)
        for step in range(0, 800, 100):
            draw.line([(step, 0), (step, 800)], fill=(180, 180, 180))
            draw.line([(0, step), (800, step)], fill=(180, 180, 180))
        return image

    board = render_board(rng, style, sample_position(rng)[0], 480, False).image
    if kind == "two_boards":
        second = render_board(rng, style, sample_position(rng)[0], 480, False).image
        image = Image.new("RGB", (1040, 520), (30, 30, 30))
        image.paste(board, (20, 20))
        image.paste(second, (540, 20))
        return image
    if kind == "cropped":
        return board.crop((0, 0, 480, rng.randint(200, 330)))
    if kind == "blurred":
        return board.filter(ImageFilter.GaussianBlur(rng.uniform(14, 22)))
    raise ValueError(kind)


REFUSALS = {
    "no_board": "no_board_detected",
    "noise": "no_board_detected",
    "table": "no_board_detected",
    "two_boards": "multiple_boards_detected",
    "cropped": "board_incomplete",
    "blurred": "image_too_blurry",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("out", type=Path)
    parser.add_argument("--split", choices=["train", "calibration", "holdout"], required=True)
    parser.add_argument("--boards", type=int, default=300)
    parser.add_argument("--refusals-each", type=int, default=5)
    parser.add_argument("--seed", type=int, default=5_000_000)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    args.out.mkdir(parents=True, exist_ok=True)
    entries = [labelled_entry(i, args.split, rng, args.out) for i in range(args.boards)]

    for kind, code in REFUSALS.items():
        for index in range(args.refusals_each):
            name = f"images/refuse-{kind}-{index}.png"
            write_image(args.out / name, refusal_image(kind, args.split, rng), rng)
            entries.append(
                {
                    "id": f"refuse-{kind}-{index}",
                    "image": name,
                    "kind": "screenshot",
                    "set_id": f"refusals-{args.split}",
                    "split": "holdout" if args.split == "holdout" else "dev",
                    "source": "generated by ptc_data",
                    "license": "testing only",
                    "expected_failure": code,
                    "tags": [kind],
                }
            )

    manifest = args.out / "manifest.jsonl"
    manifest.write_text("\n".join(json.dumps(e) for e in entries) + "\n", encoding="utf-8")
    print(f"Wrote {len(entries)} images to {args.out}")


if __name__ == "__main__":
    main()
